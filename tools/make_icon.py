"""
Generates the Fast Launcher app icon: an adaptive icon (vector layers) plus an SVG preview.

The mark is a white pebble, the same superposition-of-lobes blob the launcher draws behind
every app icon, carrying two stacked upward chevrons: the swipe-up drawer, and speed.

    python tools/make_icon.py
"""
import math
import os

ROOT = os.path.join(os.path.dirname(__file__), "..")
SIZE = 108  # adaptive icon viewport; the middle 72 is what launchers show, 66 is always safe


def pebble(cx, cy, r, seed=7, turn=0.35, steps=72):
    """Same idea as Icons.blob(): a circle nudged by a few soft lobes, quadratic-smoothed."""
    import random
    rnd = random.Random(seed)
    p2, p3, p5 = (rnd.random() * math.tau for _ in range(3))
    a2, a3, a5 = 0.035, 0.040, 0.012
    rad = [1 + a2 * math.sin(2 * (t := math.tau * i / steps + turn) + p2) + a3 * math.sin(3 * t + p3)
           + a5 * math.sin(5 * t + p5) for i in range(steps)]
    m = max(rad)
    pts = [(cx + r * rad[i] / m * math.cos(math.tau * i / steps),
            cy + r * rad[i] / m * math.sin(math.tau * i / steps)) for i in range(steps)]
    mid = lambda a, b: ((a[0] + b[0]) / 2, (a[1] + b[1]) / 2)
    d = "M%.2f,%.2f" % mid(pts[-1], pts[0])
    for i in range(steps):
        q = pts[i]
        e = mid(pts[i], pts[(i + 1) % steps])
        d += " Q%.2f,%.2f %.2f,%.2f" % (q[0], q[1], e[0], e[1])
    return d + " Z"


PEBBLE = pebble(54, 53, 25)
SHADOW = pebble(54, 56.5, 25.5)
CHEVRON_TOP = "M43.5,55 L54,44.5 L64.5,55"
CHEVRON_LOW = "M43.5,65.5 L54,55 L64.5,65.5"

BG_FROM, BG_TO = "#FF10152A", "#FF2F6BF6"   # deep night -> launcher accent
MARK_FROM, MARK_TO = "#FF2F7CF6", "#FF7B5CFF"  # accent blue -> violet


def write(path, text):
    full = os.path.join(ROOT, path)
    os.makedirs(os.path.dirname(full), exist_ok=True)
    with open(full, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    print("wrote", path)


AAPT = 'xmlns:android="http://schemas.android.com/apk/res/android" xmlns:aapt="http://schemas.android.com/aapt"'


def gradient_fill(x1, y1, x2, y2, c1, c2):
    return f"""        <aapt:attr name="android:fillColor">
            <gradient android:type="linear" android:startX="{x1}" android:startY="{y1}"
                android:endX="{x2}" android:endY="{y2}"
                android:startColor="{c1}" android:endColor="{c2}" />
        </aapt:attr>"""


def gradient_stroke(x1, y1, x2, y2, c1, c2):
    return gradient_fill(x1, y1, x2, y2, c1, c2).replace("android:fillColor", "android:strokeColor")


write("res/drawable/ic_launcher_background.xml", f"""<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tools/make_icon.py -->
<vector {AAPT}
    android:width="108dp" android:height="108dp"
    android:viewportWidth="{SIZE}" android:viewportHeight="{SIZE}">
    <path android:pathData="M0,0 H{SIZE} V{SIZE} H0 Z">
{gradient_fill(0, 0, SIZE, SIZE, BG_FROM, BG_TO)}
    </path>
    <!-- a soft glow behind the pebble, fading out well before any mask edge -->
    <path android:pathData="M0,0 H{SIZE} V{SIZE} H0 Z">
        <aapt:attr name="android:fillColor">
            <gradient android:type="radial" android:centerX="54" android:centerY="52"
                android:gradientRadius="40" android:startColor="#29FFFFFF" android:endColor="#00FFFFFF" />
        </aapt:attr>
    </path>
</vector>
""")

write("res/drawable/ic_launcher_foreground.xml", f"""<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tools/make_icon.py -->
<vector {AAPT}
    android:width="108dp" android:height="108dp"
    android:viewportWidth="{SIZE}" android:viewportHeight="{SIZE}">
    <path android:pathData="{SHADOW}" android:fillColor="#FF000000" android:fillAlpha="0.28" />
    <path android:pathData="{PEBBLE}" android:fillColor="#FFFFFFFF" />
    <path android:pathData="{CHEVRON_LOW}" android:strokeWidth="5.2" android:strokeLineCap="round"
        android:strokeLineJoin="round" android:strokeAlpha="0.42">
{gradient_stroke(43, 66, 65, 54, MARK_FROM, MARK_TO)}
    </path>
    <path android:pathData="{CHEVRON_TOP}" android:strokeWidth="5.2" android:strokeLineCap="round"
        android:strokeLineJoin="round">
{gradient_stroke(43, 55, 65, 44, MARK_FROM, MARK_TO)}
    </path>
</vector>
""")

# themed icons (Android 13+): one colour, the system tints it
write("res/drawable/ic_launcher_monochrome.xml", f"""<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tools/make_icon.py -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="108dp" android:height="108dp"
    android:viewportWidth="{SIZE}" android:viewportHeight="{SIZE}">
    <path android:pathData="{PEBBLE}" android:strokeColor="#FFFFFFFF" android:strokeWidth="3.4" />
    <path android:pathData="{CHEVRON_LOW}" android:strokeColor="#FFFFFFFF" android:strokeWidth="4.6"
        android:strokeLineCap="round" android:strokeLineJoin="round" android:strokeAlpha="0.5" />
    <path android:pathData="{CHEVRON_TOP}" android:strokeColor="#FFFFFFFF" android:strokeWidth="4.6"
        android:strokeLineCap="round" android:strokeLineJoin="round" />
</vector>
""")

write("res/mipmap-anydpi-v26/ic_launcher.xml", """<?xml version="1.0" encoding="utf-8"?>
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@drawable/ic_launcher_background" />
    <foreground android:drawable="@drawable/ic_launcher_foreground" />
    <monochrome android:drawable="@drawable/ic_launcher_monochrome" />
</adaptive-icon>
""")

# preview: the full 108 layer, plus how launchers mask it (squircle-ish) at 72/108
svg = f"""<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {SIZE * 3 + 40} {SIZE + 20}" width="{(SIZE * 3 + 40) * 4}" height="{(SIZE + 20) * 4}">
  <defs>
    <linearGradient id="bg" x1="0" y1="0" x2="1" y2="1"><stop offset="0" stop-color="#10152A"/><stop offset="1" stop-color="#2F6BF6"/></linearGradient>
    <linearGradient id="mk" x1="0" y1="1" x2="1" y2="0"><stop offset="0" stop-color="#2F7CF6"/><stop offset="1" stop-color="#7B5CFF"/></linearGradient>
    <radialGradient id="gl" cx="0.5" cy="0.5" r="0.5"><stop offset="0" stop-color="#fff" stop-opacity="0.16"/><stop offset="1" stop-color="#fff" stop-opacity="0"/></radialGradient>
    <clipPath id="sq"><rect x="18" y="18" width="72" height="72" rx="20"/></clipPath>
    <clipPath id="ci"><circle cx="54" cy="54" r="36"/></clipPath>
    <g id="icon">
      <rect width="{SIZE}" height="{SIZE}" fill="url(#bg)"/>
      <circle cx="54" cy="52" r="40" fill="url(#gl)"/>
      <path d="{SHADOW}" fill="#000" fill-opacity="0.28"/>
      <path d="{PEBBLE}" fill="#fff"/>
      <path d="{CHEVRON_LOW}" fill="none" stroke="url(#mk)" stroke-width="5.2" stroke-linecap="round" stroke-linejoin="round" stroke-opacity="0.42"/>
      <path d="{CHEVRON_TOP}" fill="none" stroke="url(#mk)" stroke-width="5.2" stroke-linecap="round" stroke-linejoin="round"/>
    </g>
  </defs>
  <rect width="100%" height="100%" fill="#e9ebf0"/>
  <g transform="translate(10,10)"><use href="#icon"/></g>
  <g transform="translate({SIZE + 10},10)"><g clip-path="url(#sq)"><use href="#icon"/></g></g>
  <g transform="translate({SIZE * 2 + 20},10)"><g clip-path="url(#ci)"><use href="#icon"/></g></g>
</svg>
"""
write("docs/icon.svg", svg)
